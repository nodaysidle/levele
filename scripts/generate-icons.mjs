// Generates the icon library used by the canvas. Icons are stored as inner SVG
// markup so we can recolor them at runtime and rasterize them for Konva/export.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const ICONS = {
  Social: [
    "instagram", "facebook", "twitter", "linkedin", "youtube", "at-sign",
    "message-circle", "send", "heart", "thumbs-up", "share-2", "hash",
  ],
  Symbols: [
    "star", "sparkles", "zap", "flame", "crown", "gift", "party-popper",
    "cake", "music", "headphones", "play", "camera", "palette", "brush",
    "pencil", "pen-tool", "scissors", "wand-sparkles", "lightbulb", "rocket",
    "trophy", "award", "target", "infinity", "quote", "check", "x", "plus",
    "arrow-right", "arrow-up-right", "circle", "square", "triangle", "hexagon",
    "diamond", "flower", "leaf", "sun", "moon", "snowflake", "droplet", "cloud",
    "eye", "lock", "key", "shield", "bell", "bookmark",
  ],
  Life: [
    "coffee", "pizza", "ice-cream-cone", "cherry", "apple", "wine", "utensils",
    "shopping-bag", "shopping-cart", "tag", "credit-card", "dollar-sign",
    "briefcase", "building-2", "phone", "mail", "calendar", "clock", "globe",
    "map-pin", "plane", "train-front", "car", "bike", "mountain", "tree-pine",
    "tent", "palmtree", "sailboat", "house", "dog", "cat", "bird",
  ],
  Tech: [
    "code", "cpu", "smartphone", "laptop", "wifi", "battery", "database",
    "terminal", "gamepad-2", "bluetooth", "settings", "search", "home", "user",
    "users", "download", "upload", "link", "external-link", "grid-3x3",
  ],
};

const root = join(process.cwd(), "node_modules", "lucide-static", "icons");
const entries = [];
const missing = [];
let id = 0;
for (const [category, names] of Object.entries(ICONS)) {
  for (const name of names) {
    const file = join(root, `${name}.svg`);
    if (!existsSync(file)) {
      missing.push(name);
      continue;
    }
    const raw = readFileSync(file, "utf8");
    const inner = raw
      .replace(/<!--[\s\S]*?-->/g, "")
      .replace(/^[\s\S]*?<svg[^>]*>/, "")
      .replace(/<\/svg>[\s\S]*$/, "")
      .replace(/\s{2,}/g, " ")
      .trim();
    entries.push({
      id: `i${id++}`,
      name,
      label: name.replace(/-/g, " ").replace(/\b\w/g, (c) => c.toUpperCase()),
      category,
      svg: inner,
    });
  }
}

if (missing.length) console.warn("Missing icons:", missing.join(", "));

const out = `// AUTO-GENERATED by scripts/generate-icons.mjs — do not edit by hand.
// Icon artwork: Lucide (ISC license, https://lucide.dev).
export type IconDef = { id: string; name: string; label: string; category: string; svg: string };
export const ICONS: IconDef[] = ${JSON.stringify(entries, null, 2)};
export const ICON_CATEGORIES = ${JSON.stringify(Object.keys(ICONS))};
export const ICONS_BY_NAME: Record<string, IconDef> = Object.fromEntries(ICONS.map((i) => [i.name, i]));
`;
writeFileSync(join(process.cwd(), "src", "lib", "editor", "icons.ts"), out);
console.log(`Wrote ${entries.length} icons`);
